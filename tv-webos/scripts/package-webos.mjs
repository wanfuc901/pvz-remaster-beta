// Build the packaged webOS launcher app.
//
//   npm run package:webos -- --server http://192.168.1.10:8686
//
// Output: webos/build/ (app folder) and, when the webOS CLI (ares-package) is
// installed, an .ipk in webos/. See docs/WEBOS.md for installing it on a TV
// in Developer Mode.
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'webos', 'launcher');
const out = path.join(root, 'webos', 'build');

const args = process.argv.slice(2);
const i = args.indexOf('--server');
let server = i >= 0 ? args[i + 1] : process.env.TVWEBOS_SERVER || '';
if (server && !/^https?:\/\//i.test(server)) server = 'http://' + server;
if (server && !/^https?:\/\/[^/]+$/i.test(server.replace(/\/+$/, ''))) {
  console.error(`Invalid --server "${server}". Use e.g. http://192.168.1.10:8686`);
  process.exit(1);
}
server = server.replace(/\/+$/, '');

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
cpSync(src, out, { recursive: true });
writeFileSync(
  path.join(out, 'config.js'),
  `// Generated by scripts/package-webos.mjs\nwindow.TVWEBOS_SERVER = ${JSON.stringify(server)};\n`,
);

const info = JSON.parse(readFileSync(path.join(out, 'appinfo.json'), 'utf8'));
console.log(`Prepared ${info.id} ${info.version} in ${path.relative(root, out)}`);
console.log(server ? `  Server: ${server}` : '  Server: not set (the app asks on first start)');

if (!existsSync(path.join(out, 'webOSTV.js'))) {
  console.warn(
    '\n  WARNING: webOSTV.js not found in webos/launcher/.\n' +
      '  Download webOSTV.js from the LG webOS TV developer site and copy it to webos/launcher/webOSTV.js.\n' +
      '  Without it the app still runs the desktop, but launching TV apps and device info are unavailable.\n',
  );
}

const ares = spawnSync(process.platform === 'win32' ? 'ares-package.cmd' : 'ares-package', ['--version'], { encoding: 'utf8' });
if (ares.error || ares.status !== 0) {
  console.log(
    '\nares-package (webOS CLI) is not installed, so no .ipk was created.\n' +
      'Install it with:  npm install -g @webos-tools/cli\n' +
      'then run:         ares-package webos/build -o webos\n',
  );
  process.exit(0);
}
const pkg = spawnSync(process.platform === 'win32' ? 'ares-package.cmd' : 'ares-package', [out, '-o', path.join(root, 'webos')], {
  stdio: 'inherit',
});
process.exit(pkg.status ?? 1);
